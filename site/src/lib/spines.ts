/** "John 3:16", "Ps 46:10", "1 Cor 10:13": the short reference written on a spine. */
export function spineLabel(ref: PassageRef): string {
  const book = abbreviations[ref.book] ?? ref.book;
  return `${book} ${ref.chapter}:${ref.start}${ref.end > ref.start ? `-${ref.end}` : ""}`;
}
